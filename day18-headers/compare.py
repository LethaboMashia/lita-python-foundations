"""
compare.py: D18 before/after proof, generated by code.
Sends the same requests to the baseline (app.py) and hardened (secure_app.py)
apps in-process and scores every response with my Security Header Auditor.
Prints a Markdown table for the README. Exit code 1 if hardened is below 100.
Run from the repo root:  python day18-headers/compare.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "security-header-auditor"))

from auditor import audit, rating   # my own Security Header Auditor
import app as baseline              # app.py (no headers)
import secure_app as hardened       # secure_app.py (six headers)

PATHS = ["/", "/about", "/does-not-exist", "/static/style.css"]


def score_for(flask_app, path):
    with flask_app.test_client() as client:
        response = client.get(path)
    score, _ = audit(response.headers)
    return response.status_code, score


def main():
    print("| Path | Status | Baseline | Hardened |")
    print("|---|---|---|---|")
    all_strong = True
    for path in PATHS:
        status, before = score_for(baseline.app, path)
        _, after = score_for(hardened.app, path)
        all_strong = all_strong and after == 100
        print(f"| `{path}` | {status} | {before}/100 ({rating(before)}) | {after}/100 ({rating(after)}) |")
    return 0 if all_strong else 1


if __name__ == "__main__":
    sys.exit(main())
